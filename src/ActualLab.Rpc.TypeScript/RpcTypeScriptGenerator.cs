using System.Globalization;
using System.Text;

namespace ActualLab.Rpc.TypeScript;

/// <summary>
/// Generates a TypeScript module with service interfaces, DTOs and <c>defineRpcService</c> definitions
/// for a set of <see cref="RpcServiceDef"/>-s, so a TypeScript client can't drift from the .NET contracts.
/// </summary>
public sealed class RpcTypeScriptGenerator(RpcTypeScriptGeneratorOptions options)
{
    private static readonly string[] ImportedNames = ["AsyncContext", "RpcStream", "RpcType", "defineRpcService"];

    public RpcTypeScriptGeneratorOptions Options { get; } = options;

    public RpcTypeScriptGenerator() : this(RpcTypeScriptGeneratorOptions.Default) { }

    public RpcTypeScriptGeneratorResult Generate(IEnumerable<RpcServiceDef> services)
    {
        var serviceList = services
            .Where(s => !s.IsSystem)
            .OrderBy(s => s.Name, StringComparer.Ordinal)
            .ToList();
        var mapper = new TypeScriptTypeMapper(Options.JsonOptions, Options.KnownTypes);
        foreach (var name in ImportedNames)
            mapper.ReserveName(name, "import");
        foreach (var service in serviceList) {
            mapper.ReserveName(service.Type.Name, service.Type);
            mapper.ReserveName(GetDefinitionName(service), service);
        }

        var context = new GenerationContext(mapper);
        var serviceBlocks = serviceList.Select(s => GenerateService(s, context)).ToList();

        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("// Generated by ActualLab.Rpc.TypeScript");
        if (!Options.SourceName.IsNullOrEmpty())
            sb.Append(" from ").Append(Options.SourceName);
        sb.Append(". Don't edit it: change the .NET contracts and regenerate it instead.\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("/* eslint-disable */\n\n");
        if (context.UsesAsyncContext)
            sb.Append("import type { AsyncContext } from ").Append(TypeScriptSyntax.Quote(Options.CoreModule)).Append(";\n");
        var rpcImports = new List<string> { "defineRpcService" };
        if (context.UsesRpcType)
            rpcImports.Add("RpcType");
        if (context.UsesRpcStream)
            rpcImports.Add("type RpcStream");
        sb.Append("import { ").AppendJoin(", ", rpcImports).Append(" } from ")
            .Append(TypeScriptSyntax.Quote(Options.RpcModule)).Append(";\n");
        foreach (var block in serviceBlocks.Concat(mapper.Declarations))
            sb.Append('\n').Append(block).Append('\n');

        return new RpcTypeScriptGeneratorResult(sb.ToString(), context.Warnings.Concat(mapper.Warnings).ToList());
    }

    public static string GetDefinitionName(RpcServiceDef service)
    {
        var name = service.Type.Name;
        if (name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1]))
            name = name[1..];
        return name + "Def";
    }

    // Private methods

    private static string GenerateService(RpcServiceDef service, GenerationContext context)
    {
        var methods = new List<(RpcMethodDef Method, string Name, int WireArgCount)>();
        foreach (var method in service.Methods.OrderBy(m => m.MethodInfo.MetadataToken)) {
            if (!method.IsValid || method.IsSystem || method.IsBackend)
                continue;

            var colonIndex = method.Name.LastIndexOf(':');
            if (colonIndex < 0
                || !int.TryParse(method.Name.AsSpan(colonIndex + 1), CultureInfo.InvariantCulture, out var wireArgCount)) {
                context.Warnings.Add($"'{method.FullName}' is skipped: TypeScript clients require "
                    + "'Name:ArgumentCount' wire method names.");
                continue;
            }

            methods.Add((method, method.Name[..colonIndex], wireArgCount));
        }
        var overloadedNames = methods
            .GroupBy(m => m.Name, StringComparer.Ordinal)
            .Where(g => g.Count() > 1)
            .Select(g => g.Key)
            .ToHashSet(StringComparer.Ordinal);

        var interfaceSb = new StringBuilder();
        interfaceSb.Append("export interface ").Append(service.Type.Name).Append(" {\n");
        var definitionSb = new StringBuilder();
        definitionSb.Append("export const ").Append(GetDefinitionName(service))
            .Append(" = defineRpcService(").Append(TypeScriptSyntax.Quote(service.Name)).Append(", {\n");
        foreach (var (method, name, wireArgCount) in methods) {
            var parameters = method.Parameters
                .Where((_, i) => i != method.CancellationTokenIndex)
                .Select(p => (p.Name ?? "arg", Type: MapParameter(p, context)))
                .ToList();
            var isCompute = method.CallType.Id == RpcCallTypeIds.Compute;
            var isStream = IsRpcStream(method.UnwrappedReturnType);

            var signature = parameters
                .Select(p => $"{TypeScriptSyntax.ParameterName(p.Item1)}: {p.Type}")
                .ToList();
            if (isCompute) {
                signature.Add("ctx?: AsyncContext");
                context.UsesAsyncContext = true;
            }
            interfaceSb.Append("    ").Append(name)
                .Append('(').AppendJoin(", ", signature).Append("): ")
                .Append(MapReturnType(method, context)).Append(";\n");

            var entry = new List<string> {
                $"args: [{string.Join(", ", parameters.Select(p => GetArgumentSample(p.Type)))}]",
            };
            if (method.NoWait || isStream) {
                entry.Add(method.NoWait ? "returns: RpcType.noWait" : "returns: RpcType.stream");
                context.UsesRpcType = true;
            }
            if (method.CallType.Id != RpcCallTypeIds.Regular)
                entry.Add($"callTypeId: {method.CallType.Id.ToString(CultureInfo.InvariantCulture)}");
            if (wireArgCount != parameters.Count + 1)
                entry.Add($"wireArgCount: {wireArgCount.ToString(CultureInfo.InvariantCulture)}");
            if (!method.NoWait && method.RemoteExecutionMode != RpcRemoteExecutionMode.Default)
                entry.Add($"remoteExecutionMode: {((int)method.RemoteExecutionMode).ToString(CultureInfo.InvariantCulture)}");
            var key = overloadedNames.Contains(name)
                ? TypeScriptSyntax.Quote($"{name}:{wireArgCount.ToString(CultureInfo.InvariantCulture)}")
                : TypeScriptSyntax.PropertyName(name);
            definitionSb.Append("    ").Append(key).Append(": { ").AppendJoin(", ", entry).Append(" },\n");
        }
        interfaceSb.Append('}');
        definitionSb.Append("});");
        return $"{interfaceSb}\n\n{definitionSb}";
    }

    private static string MapParameter(ParameterInfo parameter, GenerationContext context)
    {
        var type = parameter.ParameterType;
        if (IsRpcStream(type)) {
            context.UsesRpcStream = true;
            return $"RpcStream<{context.Mapper.Map(type.GetGenericArguments()[0])}>";
        }

        var isNullable = context.NullabilityContext.Create(parameter).ReadState == NullabilityState.Nullable;
        return context.Mapper.Map(type, isNullable);
    }

    private static string MapReturnType(RpcMethodDef method, GenerationContext context)
    {
        var type = method.UnwrappedReturnType;
        if (method.NoWait || type == typeof(void) || type == typeof(Unit))
            return "Promise<void>";

        if (IsRpcStream(type)) {
            context.UsesRpcStream = true;
            return $"Promise<RpcStream<{context.Mapper.Map(type.GetGenericArguments()[0])}>>";
        }

        var returnInfo = context.NullabilityContext.Create(method.MethodInfo.ReturnParameter);
        var isNullable = returnInfo.GenericTypeArguments is [{ ReadState: NullabilityState.Nullable }];
        return $"Promise<{context.Mapper.Map(type, isNullable)}>";
    }

    private static bool IsRpcStream(Type type)
        => type.IsGenericType && type.GetGenericTypeDefinition() == typeof(RpcStream<>);

    private static string GetArgumentSample(string type)
        => type switch {
            _ when type.StartsWith("string", StringComparison.Ordinal) => "''",
            _ when type.StartsWith("number", StringComparison.Ordinal) => "0",
            _ when type.StartsWith("boolean", StringComparison.Ordinal) => "false",
            _ when type.EndsWith("[]", StringComparison.Ordinal) => "[]",
            _ => "{}",
        };

    // Nested types

    private sealed class GenerationContext(TypeScriptTypeMapper mapper)
    {
        public readonly TypeScriptTypeMapper Mapper = mapper;
        public readonly NullabilityInfoContext NullabilityContext = new();
        public readonly List<string> Warnings = new();
        public bool UsesAsyncContext;
        public bool UsesRpcType;
        public bool UsesRpcStream;
    }
}

public sealed record RpcTypeScriptGeneratorResult(string Code, IReadOnlyList<string> Warnings);
